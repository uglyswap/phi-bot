import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { parse as parseDotenv } from "dotenv";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
  PHIBOT_ADAPTERS_JSON,
  appendMissingEnvEntries,
  applyExposureToInstance,
  buildPhibotConfig,
  buildPhibotEnvEntries,
  resolveContainerExposure,
  resolveExposure,
  writeInstanceFiles,
} from "../phibot/instance-config.js";

const ROOT = "/var/lib/phibot/.paperclip/instances/default";
const NOW = new Date("2026-10-08T12:00:00.000Z");
const SECRET_KEYS = ["PAPERCLIP_AGENT_JWT_SECRET", "PAPERCLIP_TOOL_ACTION_SIGNING_SECRET"];

describe("resolveExposure", () => {
  it("maps --domain, --access ssh and --access tailscale", () => {
    expect(resolveExposure({ access: "domain", domain: "Bot.Exemple.fr" })).toEqual({
      access: "domain", publicUrl: "https://bot.exemple.fr", allowedHostnames: ["bot.exemple.fr"], explicitBaseUrl: true, bindHost: "127.0.0.1",
    });
    expect(resolveExposure({ access: "ssh" })).toEqual({
      access: "ssh", publicUrl: "http://localhost:3100", allowedHostnames: [], explicitBaseUrl: false, bindHost: "127.0.0.1",
    });
    expect(resolveExposure({ access: "tailscale", tailnetName: "srv.tail1234.ts.net" })).toEqual({
      access: "tailscale", publicUrl: "https://srv.tail1234.ts.net", allowedHostnames: ["srv.tail1234.ts.net"], explicitBaseUrl: true, bindHost: "127.0.0.1",
    });
  });

  it("reads PAPERCLIP_PUBLIC_URL and PAPERCLIP_ALLOWED_HOSTNAMES in the container", () => {
    expect(resolveContainerExposure({ PAPERCLIP_PUBLIC_URL: "https://bot.exemple.fr/", PAPERCLIP_ALLOWED_HOSTNAMES: "a.exemple.fr, B.exemple.fr" })).toEqual({
      access: "container", publicUrl: "https://bot.exemple.fr", allowedHostnames: ["a.exemple.fr", "b.exemple.fr", "bot.exemple.fr"], explicitBaseUrl: true, bindHost: "0.0.0.0",
    });
    expect(resolveContainerExposure({})).toEqual({
      access: "container", publicUrl: "http://localhost:3100", allowedHostnames: [], explicitBaseUrl: false, bindHost: "0.0.0.0",
    });
    expect(() => resolveContainerExposure({ PAPERCLIP_PUBLIC_URL: "ftp://x" })).toThrow("PAPERCLIP_PUBLIC_URL invalide");
  });
});

describe("buildPhibotConfig", () => {
  it("writes authenticated, private, loopback and an explicit URL for a domain", () => {
    expect(buildPhibotConfig({ instanceRoot: ROOT, exposure: resolveExposure({ access: "domain", domain: "bot.exemple.fr" }), now: NOW })).toEqual({
      $meta: { version: 1, updatedAt: "2026-10-08T12:00:00.000Z", source: "onboard" },
      database: {
        mode: "embedded-postgres",
        embeddedPostgresDataDir: `${ROOT}/db`,
        embeddedPostgresPort: 54329,
        backup: { enabled: true, intervalMinutes: 60, retentionDays: 30, dir: `${ROOT}/data/backups` },
      },
      logging: { mode: "file", logDir: `${ROOT}/logs` },
      server: {
        deploymentMode: "authenticated",
        exposure: "private",
        bind: "loopback",
        customBindHost: undefined,
        host: "127.0.0.1",
        port: 3100,
        allowedHostnames: ["bot.exemple.fr"],
        serveUi: true,
      },
      auth: { baseUrlMode: "explicit", publicBaseUrl: "https://bot.exemple.fr", disableSignUp: false },
      telemetry: { enabled: false },
      storage: {
        provider: "local_disk",
        localDisk: { baseDir: `${ROOT}/data/storage` },
        s3: { bucket: "paperclip", region: "us-east-1", prefix: "", forcePathStyle: false },
      },
      secrets: { provider: "local_encrypted", strictMode: false, localEncrypted: { keyFilePath: `${ROOT}/secrets/master.key` } },
    });
  });

  it("writes auth auto for ssh and binds 0.0.0.0 in the container", () => {
    const ssh = buildPhibotConfig({ instanceRoot: ROOT, exposure: resolveExposure({ access: "ssh" }), now: NOW });
    expect(ssh.auth).toEqual({ baseUrlMode: "auto", disableSignUp: false });
    expect(ssh.server.allowedHostnames).toEqual([]);
    const container = buildPhibotConfig({ instanceRoot: ROOT, exposure: resolveContainerExposure({}), now: NOW });
    expect(container.server.host).toBe("0.0.0.0");
    expect(container.server.bind).toBe("lan");
  });
});

describe(".env of annex A", () => {
  it("appends the missing keys unquoted and dotenv reads them back exactly", () => {
    const entries = buildPhibotEnvEntries({ publicUrl: "https://bot.exemple.fr", adaptersPath: `${ROOT}/adapters.json`, betterAuthSecret: "a".repeat(64) });
    const header = "# Paperclip environment variables\n# Generated by Paperclip CLI commands\nPAPERCLIP_AGENT_JWT_SECRET=abc\n";
    const { contents, added } = appendMissingEnvEntries(header, entries);
    expect(added).toEqual(Object.keys(entries));
    expect(contents).toBe(
      `${header}BETTER_AUTH_SECRET=${"a".repeat(64)}\n` +
        "PAPERCLIP_PUBLIC_URL=https://bot.exemple.fr\n" +
        "PAPERCLIP_API_URL=http://127.0.0.1:3100\n" +
        `PAPERCLIP_ADAPTERS_FILE=${ROOT}/adapters.json\n` +
        "PAPERCLIP_HIDDEN_SETTINGS=instance.adapters,instance.plugins,instance.experimental,instance.environments,company.import,instance.general.feedbackDataSharingPreference\n" +
        "PAPERCLIP_ONBOARDING_SEED_ADAPTER_TYPE=phi_local\n" +
        "PAPERCLIP_TEAMS_CATALOG_DEFAULT_ADAPTER_TYPE=phi_local\n" +
        "PAPERCLIP_TELEMETRY_DISABLED=1\n" +
        "PAPERCLIP_ANNOUNCEMENTS_ENABLED=false\n" +
        "PAPERCLIP_FEEDBACK_EXPORT_BACKEND_URL=http://127.0.0.1:9\n" +
        'PAPERCLIP_SETTING_DEFAULTS={"feedbackDataSharingPreference":"not_allowed"}\n' +
        "PAPERCLIP_MIGRATION_AUTO_APPLY=true\n" +
        "PAPERCLIP_UPDATE_CHECK=0\n" +
        "PAPERCLIP_DISABLE_CWD_ENV_FILE=true\n" +
        "PHIBOT_SINGLE_COMPANY=true\n" +
        "PHIBOT_INVITE_ONLY_SIGNUP=true\n" +
        "PHIBOT_DISABLE_BROWSER_CLAIM=true\n",
    );
    expect(parseDotenv(contents)).toEqual({ PAPERCLIP_AGENT_JWT_SECRET: "abc", ...entries });
  });

  it("never changes an existing assignment", () => {
    const { contents, added } = appendMissingEnvEntries("PAPERCLIP_PUBLIC_URL=https://old.example\n", { PAPERCLIP_PUBLIC_URL: "https://new.example", PHIBOT_SINGLE_COMPANY: "true" });
    expect(added).toEqual(["PHIBOT_SINGLE_COMPANY"]);
    expect(contents).toBe("PAPERCLIP_PUBLIC_URL=https://old.example\nPHIBOT_SINGLE_COMPANY=true\n");
  });
});

describe("writeInstanceFiles", () => {
  let root: string;
  beforeEach(() => {
    root = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "phibot-instance-")), "instances", "default");
    for (const key of SECRET_KEYS) delete process.env[key];
  });
  afterEach(() => {
    for (const key of SECRET_KEYS) delete process.env[key];
    fs.rmSync(path.dirname(path.dirname(root)), { recursive: true, force: true });
  });

  it("creates config.json, .env, adapters.json and master.key, then keeps them", () => {
    process.env.PAPERCLIP_AGENT_JWT_SECRET = "secret-of-another-instance";
    const exposure = resolveExposure({ access: "ssh" });
    const first = writeInstanceFiles({ instanceRoot: root, exposure, now: NOW });
    expect(first.touchedFiles).toEqual([
      path.join(root, "config.json"), path.join(root, ".env"), path.join(root, "adapters.json"), path.join(root, "secrets", "master.key"),
    ]);
    expect(first.createdDirs).toEqual([root, path.join(root, "secrets")]);
    const env = parseDotenv(fs.readFileSync(path.join(root, ".env"), "utf8"));
    expect(env.PAPERCLIP_AGENT_JWT_SECRET).toMatch(/^[0-9a-f]{64}$/);
    expect(env.PAPERCLIP_TOOL_ACTION_SIGNING_SECRET).toMatch(/^[0-9a-f]{64}$/);
    expect(env.BETTER_AUTH_SECRET).toMatch(/^[0-9a-f]{64}$/);
    expect(env.PAPERCLIP_PUBLIC_URL).toBe("http://localhost:3100");
    expect(fs.readFileSync(path.join(root, "adapters.json"), "utf8")).toBe(PHIBOT_ADAPTERS_JSON);
    expect(JSON.parse(fs.readFileSync(path.join(root, "config.json"), "utf8")).auth).toEqual({ baseUrlMode: "auto", disableSignUp: false });

    const envBefore = fs.readFileSync(path.join(root, ".env"), "utf8");
    const keyBefore = fs.readFileSync(path.join(root, "secrets", "master.key"), "utf8");
    const second = writeInstanceFiles({ instanceRoot: root, exposure: resolveExposure({ access: "domain", domain: "bot.exemple.fr" }), now: NOW });
    expect(second).toEqual({ touchedFiles: [], createdDirs: [], envKeysAdded: [] });
    expect(fs.readFileSync(path.join(root, ".env"), "utf8")).toBe(envBefore);
    expect(fs.readFileSync(path.join(root, "secrets", "master.key"), "utf8")).toBe(keyBefore);
  });

  it("switches the access without touching secrets (setup --reconfigure)", () => {
    writeInstanceFiles({ instanceRoot: root, exposure: resolveExposure({ access: "ssh" }), now: NOW });
    const jwtBefore = parseDotenv(fs.readFileSync(path.join(root, ".env"), "utf8")).PAPERCLIP_AGENT_JWT_SECRET;
    const touched = applyExposureToInstance({ instanceRoot: root, exposure: resolveExposure({ access: "domain", domain: "bot.exemple.fr" }) });
    expect(touched).toEqual([path.join(root, "config.json"), path.join(root, ".env")]);
    const config = JSON.parse(fs.readFileSync(path.join(root, "config.json"), "utf8"));
    expect(config.auth).toEqual({ baseUrlMode: "explicit", publicBaseUrl: "https://bot.exemple.fr", disableSignUp: false });
    expect(config.server.allowedHostnames).toEqual(["bot.exemple.fr"]);
    const env = parseDotenv(fs.readFileSync(path.join(root, ".env"), "utf8"));
    expect(env.PAPERCLIP_PUBLIC_URL).toBe("https://bot.exemple.fr");
    expect(env.PAPERCLIP_AGENT_JWT_SECRET).toBe(jwtBefore);
  });
});
